#!/usr/bin/env node
/** Writes `THIRD-PARTY-NOTICES` from `pnpm licenses list --prod`; refuses a copyleft licence. No AWS. */
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = join(fileURLToPath(new URL(".", import.meta.url)), "..");
const out = join(repoRoot, "THIRD-PARTY-NOTICES");

const byLicence = JSON.parse(
  execFileSync("pnpm", ["licenses", "list", "--json", "--prod"], {
    cwd: repoRoot,
    encoding: "utf8",
    maxBuffer: 64 * 1024 * 1024,
  }),
);

const COPYLEFT = /\b(GPL|AGPL|LGPL|MPL|EPL|CDDL|OSL|EUPL|SSPL)\b/i;
const copyleft = Object.keys(byLicence).filter((l) => COPYLEFT.test(l));
if (copyleft.length > 0) {
  console.error(`✗ copyleft licence(s) in the production graph: ${copyleft.join(", ")}`);
  console.error("  ADR-023 chose Apache-2.0 on the basis that there are none. Decide before generating.");
  process.exit(1);
}

const licences = Object.keys(byLicence).sort();
const total = licences.reduce((n, l) => n + byLicence[l].length, 0);

const section = (licence) => {
  const packages = [...byLicence[licence]].sort((a, b) => a.name.localeCompare(b.name));
  const rows = packages.map((p) => {
    const versions = (p.versions ?? []).join(", ");
    return `  ${p.name}${versions ? ` (${versions})` : ""}${p.homepage ? ` — ${p.homepage}` : ""}`;
  });
  return `## ${licence} — ${packages.length} package(s)\n\n${rows.join("\n")}\n`;
};

writeFileSync(
  out,
  [
    "THIRD-PARTY NOTICES",
    "===================",
    "",
    "This product bundles, or depends at runtime on, the packages below. Each remains under its own",
    "licence and its own copyright; nothing here grants any right beyond what those licences give.",
    "",
    "Generated by `pnpm run generate:third-party-notices` from the production dependency graph — do",
    "not edit by hand. Development-only dependencies are excluded: they are not redistributed.",
    "",
    `${total} package(s) across ${licences.length} licence(s). None is copyleft, which is the condition`,
    "ADR-023's choice of Apache-2.0 rests on.",
    "",
    "For the Apache-2.0 works below, this file is the NOTICE propagation §4(d) asks for. A package's",
    "own NOTICE, where it ships one, travels inside its published tarball in `node_modules`.",
    "",
    ...licences.map(section),
  ].join("\n"),
);
console.log(`✓ THIRD-PARTY-NOTICES — ${total} package(s), ${licences.length} licence(s), no copyleft`);
