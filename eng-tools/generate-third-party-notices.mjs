#!/usr/bin/env node
/** Writes `THIRD-PARTY-NOTICES` from `pnpm licenses list --prod`; refuses an unreviewed copyleft licence. No AWS. */
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = join(fileURLToPath(new URL(".", import.meta.url)), "..");
const out = join(repoRoot, "THIRD-PARTY-NOTICES");

const byLicence = JSON.parse(
  execFileSync("pnpm", ["licenses", "list", "--json", "--prod"], {
    cwd: repoRoot,
    encoding: "utf8",
    maxBuffer: 64 * 1024 * 1024,
  }),
);

const COPYLEFT = /\b(GPL|AGPL|LGPL|MPL|EPL|CDDL|OSL|EUPL|SSPL)\b/i;

const REVIEWED_COPYLEFT = [
  {
    name: "elkjs",
    version: "0.11.1",
    licence: "EPL-2.0",
    source: "https://github.com/kieler/elkjs",
    reason: "Reached only via the Prisma CLI's Studio, whose prisma/build/studio.js also inlines a copy.",
  },
];

const label = (name, versions, licence) => `${name}@${versions.join("|")} (${licence})`;

const isReviewed = (licence, p) =>
  REVIEWED_COPYLEFT.some(
    (r) =>
      r.licence === licence &&
      r.name === p.name &&
      (p.versions ?? []).length > 0 &&
      p.versions.every((v) => v === r.version),
  );

const unreviewed = Object.entries(byLicence)
  .filter(([licence]) => COPYLEFT.test(licence))
  .flatMap(([licence, packages]) =>
    packages.filter((p) => !isReviewed(licence, p)).map((p) => label(p.name, p.versions ?? [], licence)),
  );
const stale = REVIEWED_COPYLEFT.filter(
  (r) => !(byLicence[r.licence] ?? []).some((p) => p.name === r.name && (p.versions ?? []).includes(r.version)),
).map((r) => label(r.name, [r.version], r.licence));

if (unreviewed.length > 0) {
  console.error(`✗ unreviewed copyleft package(s) in the production graph: ${unreviewed.join(", ")}`);
  console.error("  Each one is a decision: remove it, or review it into REVIEWED_COPYLEFT with its source and reason.");
}
if (stale.length > 0) {
  console.error(`✗ REVIEWED_COPYLEFT names package(s) no longer in the production graph: ${stale.join(", ")}`);
}
if (unreviewed.length > 0 || stale.length > 0) process.exit(1);

const licences = Object.keys(byLicence).sort();
const total = licences.reduce((n, l) => n + byLicence[l].length, 0);

const section = (licence) => {
  const packages = [...byLicence[licence]].sort((a, b) => a.name.localeCompare(b.name));
  const rows = packages.map((p) => {
    const versions = (p.versions ?? []).join(", ");
    return `  ${p.name}${versions ? ` (${versions})` : ""}${p.homepage ? ` — ${p.homepage}` : ""}`;
  });
  return `## ${licence} — ${packages.length} package(s)\n\n${rows.join("\n")}\n`;
};

const copyleftStatement =
  REVIEWED_COPYLEFT.length === 0
    ? [
        `${total} package(s) across ${licences.length} licence(s). None is copyleft, which is the condition`,
        "the project's Apache-2.0 licence rests on.",
      ]
    : [
        `${total} package(s) across ${licences.length} licence(s). None is copyleft except the reviewed package(s)`,
        "below. Each is unmodified, stays in its own files under its own licence, and is not imported by",
        "this project's code. Its source code is available at the address given.",
        "",
        ...REVIEWED_COPYLEFT.flatMap((r) => [`  ${r.name} (${r.version}) — ${r.licence} — ${r.source}`, `    ${r.reason}`]),
      ];

writeFileSync(
  out,
  [
    "THIRD-PARTY NOTICES",
    "===================",
    "",
    "This product bundles, or depends at runtime on, the packages below. Each remains under its own",
    "licence and its own copyright; nothing here grants any right beyond what those licences give.",
    "",
    "Generated by `pnpm run generate:third-party-notices` from the production dependency graph — do",
    "not edit by hand. Development-only dependencies are excluded: they are not redistributed.",
    "",
    ...copyleftStatement,
    "",
    "For the Apache-2.0 works below, this file is the NOTICE propagation §4(d) asks for. A package's",
    "own NOTICE, where it ships one, travels inside its published tarball in `node_modules`.",
    "",
    ...licences.map(section),
  ].join("\n"),
);
console.log(
  `✓ THIRD-PARTY-NOTICES — ${total} package(s), ${licences.length} licence(s), ${REVIEWED_COPYLEFT.length} reviewed copyleft package(s), no other copyleft`,
);
